"""Checksummed business archives; restore SQL is generated, never auto-executed."""

import base64
import gzip
import hashlib
import io
import json

TABLES = (
    "users",
    "trips",
    "trip_members",
    "trip_invites",
    "expenses",
    "receipt_images",
    "receipt_jobs",
    "settlement_versions",
    "share_links",
    "idempotency_keys",
    "refresh_tokens",
    "trip_ledgers",
    "payment_records",
    "payment_allocations",
)


def pack_backup(payload):
    raw = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode()
    envelope = {
        "format": "travel-split-backup-v1",
        "sha256": hashlib.sha256(raw).hexdigest(),
        "payload": payload,
    }
    return gzip.compress(json.dumps(envelope, ensure_ascii=False).encode(), mtime=0)


def unpack_backup(archive):
    with gzip.GzipFile(fileobj=io.BytesIO(archive)) as source:
        raw = source.read(50_000_001)
    if len(raw) > 50_000_000:
        raise ValueError("备份超过此工具的50MB恢复上限")
    envelope = json.loads(raw)
    if envelope.get("format") != "travel-split-backup-v1":
        raise ValueError("备份格式不匹配")
    payload = envelope["payload"]
    canonical = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode()
    if hashlib.sha256(canonical).hexdigest() != envelope["sha256"]:
        raise ValueError("备份校验失败")
    if (
        payload.get("schema_version") != "20261022_07"
        or set(payload.get("tables", {})) != set(TABLES)
        or set(payload.get("schema", {})) != set(TABLES)
    ):
        raise ValueError("备份结构或版本不匹配")
    if any(not isinstance(rows, list) for rows in payload["tables"].values()):
        raise ValueError("备份数据格式不匹配")
    return payload


def restore_sql(archive):
    payload = unpack_backup(archive)
    statements = [
        "BEGIN;",
        "-- Restore only into a new, empty environment with the matching migrations.",
    ]
    for table in TABLES:
        # All identifiers are the fixed allowlist above; data is encoded, never interpolated as SQL.
        schema = base64.b64encode(
            json.dumps(payload["schema"][table]).encode()
        ).decode()
        statements.append(
            f"DO $$ DECLARE actual jsonb; BEGIN IF EXISTS(SELECT 1 FROM public.{table}) THEN RAISE EXCEPTION 'TARGET_NOT_EMPTY'; END IF; SELECT jsonb_agg(jsonb_build_object('name',column_name,'type',udt_name) ORDER BY column_name) INTO actual FROM information_schema.columns WHERE table_schema='public' AND table_name='{table}'; IF actual IS DISTINCT FROM convert_from(decode('{schema}','base64'),'UTF8')::jsonb THEN RAISE EXCEPTION 'SCHEMA_MISMATCH'; END IF; END $$;"
        )
    for table in TABLES:
        if table in {"payment_records", "payment_allocations"}:
            continue  # Regenerated by the ledger trigger.
        rows = base64.b64encode(
            json.dumps(payload["tables"][table], ensure_ascii=False).encode()
        ).decode()
        statements.append(
            f"INSERT INTO public.{table} SELECT * FROM jsonb_populate_recordset(NULL::public.{table},convert_from(decode('{rows}','base64'),'UTF8')::jsonb);"
        )
    for table in TABLES:
        count = len(payload["tables"][table])
        statements.append(
            f"DO $$ BEGIN IF (SELECT count(*) FROM public.{table}) <> {count} THEN RAISE EXCEPTION 'RESTORE_COUNT_MISMATCH'; END IF; END $$;"
        )
    statements.append("COMMIT;")
    return "\n".join(statements)
